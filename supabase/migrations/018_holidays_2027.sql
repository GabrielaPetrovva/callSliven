-- 018_holidays_2027.sql
-- Допълва неработните дни за 2027 г. (011 съдържа само четири от тях).
--
-- Правило (чл. 154 от Кодекса на труда): когато официален празник е в събота или неделя,
-- първият (или първите два) работни дни след него са неработни. Великденските дни не се компенсират.
-- 2027: 1 май (събота) съвпада с Велика събота -> компенсира се с 4 май (вторник);
--       25 декември (събота) и 26 декември (неделя) -> 27 и 28 декември (понеделник и вторник).
--
-- ЗА ПРОВЕРКА: 4 май е единственият ден, който зависи от тълкуване. Към октомври 2026 няма публикувано
-- решение на Министерския съвет за допълнителни неприсъствени дни или разменени работни дни за 2027.
-- Ако излезе такова решение, нова миграция добавя или маха съответните дни.

insert into public.holidays (day, name) values
  ('2027-05-04', 'Неприсъствен ден (1 май е в събота)'),
  ('2027-05-06', 'Гергьовден'),
  ('2027-05-24', 'Ден на българската просвета и култура'),
  ('2027-09-06', 'Ден на Съединението'),
  ('2027-09-22', 'Ден на Независимостта'),
  ('2027-12-24', 'Бъдни вечер'),
  ('2027-12-27', 'Неприсъствен ден (25 декември е в събота)'),
  ('2027-12-28', 'Неприсъствен ден (26 декември е в неделя)')
on conflict (day) do nothing;

-- Проверка: 2027 има 261 делнични дни и 12 неработни в тях, или 249 работни дни.
do $$
declare
  off_weekdays integer;
  working integer;
begin
  select count(*) into off_weekdays
  from public.holidays h
  where h.day between '2027-01-01' and '2027-12-31' and extract(isodow from h.day) < 6;
  select count(*) into working
  from generate_series('2027-01-01'::date, '2027-12-31'::date, interval '1 day') g(d)
  where extract(isodow from g.d) < 6
    and not exists (select 1 from public.holidays h where h.day = g.d::date);
  if off_weekdays <> 12 or working <> 249 then
    raise exception 'Календарът за 2027 е неправилен: % неработни делнични дни и % работни (очаквани 12 и 249)', off_weekdays, working;
  end if;
end $$;
